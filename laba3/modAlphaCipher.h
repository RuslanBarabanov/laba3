#pragma once
#include <vector>
#include <string>
#include <map>
#include <cctype>
#include <stdexcept>

/**
 * @brief Класс исключения для ошибок шифрования
 * @details Наследуется от std::invalid_argument, используется для 
 * обработки ошибок, специфичных для операций шифрования и дешифрования.
 * 
 * @example
 * @code
 * throw cipher_error("Недопустимый символ в ключе");
 * @endcode
 */
class cipher_error : public std::invalid_argument {
public:
    /**
     * @brief Конструктор с std::string
     * @param what_arg Сообщение об ошибке
     */
    explicit cipher_error(const std::string& what_arg) : 
        std::invalid_argument(what_arg) {}
    
    /**
     * @brief Конструктор с const char*
     * @param what_arg Сообщение об ошибке
     */
    explicit cipher_error(const char* what_arg) : 
        std::invalid_argument(what_arg) {}
};

/**
 * @brief Класс для шифрования методом Гронсфельда
 * @details Реализует модифицированную версию шифра Гронсфельда
 * для работы с русским алфавитом. Поддерживает операции шифрования
 * и дешифрования с полной валидацией входных данных.
 * 
 * @warning Класс не имеет конструктора по умолчанию. Требуется указать ключ.
 * 
 * @note Алфавит: "АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ"
 */
class modAlphaCipher
{
private:
    /** @brief Строка русского алфавита для шифрования */
    std::wstring numAlpha = L"АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ";
    
    /** @brief Карта соответствия символов их индексам в алфавите */
    std::map <wchar_t,int> alphaNum;
    
    /** @brief Вектор числовых значений ключа */
    std::vector <int> key;
    
    /**
     * @brief Преобразует строку в вектор числовых индексов
     * @param s Входная строка
     * @return Вектор индексов символов в алфавите
     * @throw std::out_of_range Если символ не найден в алфавите
     */
    std::vector<int> convert(const std::wstring& s);
    
    /**
     * @brief Преобразует вектор числовых индексов в строку
     * @param v Вектор индексов
     * @return Строка символов
     */
    std::wstring convert(const std::vector<int>& v);
    
    /**
     * @brief Преобразует строку в верхний регистр
     * @param s Входная строка
     * @return Строка в верхнем регистре
     */
    std::wstring toUpperCase(const std::wstring& s);
    
    /**
     * @brief Валидирует ключ шифрования
     * @param s Ключ для проверки
     * @return Валидированный ключ в верхнем регистре
     * @throw cipher_error Если ключ пустой, содержит недопустимые символы или все символы одинаковые
     * 
     * @details Проверяет:
     * - Непустоту ключа
     * - Наличие только символов русского алфавита
     * - Неоднородность символов (не все одинаковые)
     */
    std::wstring getValidKey(const std::wstring& s);
    
    /**
     * @brief Валидирует открытый текст
     * @param s Текст для проверки
     * @return Очищенный текст (без неалфавитных символов, в верхнем регистре)
     * @throw cipher_error Если текст пустой или не содержит допустимых символов
     * 
     * @details Удаляет все символы, не входящие в русский алфавит.
     */
    std::wstring getValidOpenText(const std::wstring& s);
    
    /**
     * @brief Валидирует зашифрованный текст
     * @param s Зашифрованный текст для проверки
     * @return Текст в верхнем регистре
     * @throw cipher_error Если текст пустой или содержит недопустимые символы
     * 
     * @details Зашифрованный текст должен содержать только символы русского алфавита.
     */
    std::wstring getValidCipherText(const std::wstring& s);

public:
    /**
     * @brief Удаленный конструктор по умолчанию
     * @details Класс требует указания ключа для работы.
     */
    modAlphaCipher()=delete;
    
    /**
     * @brief Конструктор с параметром ключа
     * @param skey Ключ шифрования
     * @throw cipher_error Если ключ невалиден
     * 
     * @details Инициализирует алфавитную карту и валидирует ключ.
     */
    modAlphaCipher(const std::wstring& skey);
    
    /**
     * @brief Шифрует открытый текст
     * @param open_text Текст для шифрования
     * @return Зашифрованный текст
     * @throw cipher_error Если текст невалиден или произошла ошибка при шифровании
     * 
     * @details Алгоритм шифрования:
     * 1. Валидация и очистка входного текста
     * 2. Преобразование символов в числовые индексы
     * 3. Применение ключа по формуле: (символ + ключ) mod размер_алфавита
     * 4. Преобразование обратно в строку
     */
    std::wstring encrypt(const std::wstring& open_text);
    
    /**
     * @brief Дешифрует зашифрованный текст
     * @param cipher_text Текст для дешифрования
     * @return Расшифрованный текст
     * @throw cipher_error Если текст невалиден или произошла ошибка при дешифровании
     * 
     * @details Алгоритм дешифрования:
     * 1. Валидация зашифрованного текста
     * 2. Преобразование символов в числовые индексы
     * 3. Применение ключа по формуле: (символ + алфавит - ключ) mod размер_алфавита
     * 4. Преобразование обратно в строку
     */
    std::wstring decrypt(const std::wstring& cipher_text);
};