/**
 * @file anotherCipher.h
 * @brief Заголовочный файл для шифра перестановки по столбцам
 * @details 
 * Реализация шифра перестановки по столбцам - симметричного блочного шифра,
 * использующего табличную перестановку символов.
 * 
 * @section algorithm_sec Алгоритм шифрования
 * Алгоритм работает по следующей схеме:
 * 1. Текст записывается в таблицу построчно с заданным количеством столбцов
 * 2. Пустые ячейки заполняются пробелами
 * 3. Шифротекст формируется чтением таблицы снизу вверх по столбцам
 * 
 * @section decrypt_sec Алгоритм дешифрования
 * Для дешифрования используется обратный процесс:
 * 1. Шифротекст записывается в таблицу снизу вверх по столбцам
 * 2. Оригинальный текст читается построчно
 * 
 * @author BarabanovRuslan
 * @date 20.12.25
 * @version 1.0
 */

#pragma once

#include <string>
#include <vector>
#include <stdexcept>

/**
 * @brief Класс исключения для ошибок шифрования
 * @details Наследуется от std::invalid_argument, используется для 
 * обработки ошибок, специфичных для операций шифрования и дешифрования
 * шифра перестановки по столбцам.
 * 
 * @example
 * @code
 * throw cipher_error("Недопустимый символ в ключе");
 * @endcode
 */
class cipher_error : public std::invalid_argument {
public:
    /**
     * @brief Конструктор с std::string
     * @param what_arg Сообщение об ошибке
     */
    explicit cipher_error(const std::string& what_arg) : 
        std::invalid_argument(what_arg) {}
    
    /**
     * @brief Конструктор с const char*
     * @param what_arg Сообщение об ошибке
     */
    explicit cipher_error(const char* what_arg) : 
        std::invalid_argument(what_arg) {}
};

/**
 * @brief Шифрует текст методом перестановки по столбцам
 * @param plaintext Открытый текст для шифрования
 * @param columns Количество столбцов в таблице перестановки (1-100)
 * @return Зашифрованный текст
 * @throw cipher_error Если параметры невалидны или произошла ошибка шифрования
 * 
 * @details Текст записывается в таблицу построчно, затем читается снизу вверх
 * по столбцам. Пустые ячейки заполняются пробелами.
 * 
 * @note Пример работы алгоритма:
 * Текст: "HELLO", столбцов: 2
 * Таблица: H E
 *          L L
 *          O
 * Чтение снизу вверх: O L L E H -> "OLLEH"
 */
std::string encrypt(const std::string& plaintext, int columns);

/**
 * @brief Дешифрует текст, зашифрованный методом перестановки по столбцам
 * @param ciphertext Зашифрованный текст
 * @param columns Количество столбцов в таблице перестановки (1-100)
 * @return Расшифрованный текст
 * @throw cipher_error Если параметры невалидны или произошла ошибка дешифрования
 * 
 * @details Шифротекст записывается в таблицу снизу вверх по столбцам,
 * затем читается построчно для восстановления исходного текста.
 */
std::string decrypt(const std::string& ciphertext, int columns);

// Вспомогательные функции для валидации

/**
 * @brief Валидирует ключ (количество столбцов)
 * @param columns Количество столбцов для проверки
 * @return Валидное количество столбцов
 * @throw cipher_error Если columns <= 0 или columns > 100
 * 
 * @details Допустимый диапазон: 1-100 столбцов.
 */
int getValidKey(int columns);

/**
 * @brief Валидирует открытый текст
 * @param text Текст для проверки
 * @return Валидный открытый текст
 * @throw cipher_error Если текст пустой или не содержит печатных символов
 * 
 * @details Текст должен содержать хотя бы один непробельный печатный символ.
 * Пробелы в тексте сохраняются, но в таблице они могут изменить позицию.
 */
std::string getValidOpenText(const std::string& text);

/**
 * @brief Валидирует зашифрованный текст
 * @param text Зашифрованный текст для проверки
 * @return Валидный зашифрованный текст
 * @throw cipher_error Если текст пустой или содержит непечатные символы
 * 
 * @details Зашифрованный текст должен состоять только из печатных символов.
 * Это необходимо для корректного заполнения таблицы при дешифровании.
 */
std::string getValidCipherText(const std::string& text);